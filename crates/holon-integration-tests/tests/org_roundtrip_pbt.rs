#[test]
fn sanity_edge_abstraction_tag_roundtrips() {
    // The May 2026 :edge_abstraction: drop case.
    let tops = vec![GenBlock {
        id: "n0".into(),
        content: "headline".into(),
        tags: vec!["edge_abstraction".into()],
        properties: vec![],
        todo: None,
        children: vec![],
    }];
    run_case(&tops).expect("edge_abstraction tag must survive round-trip");
}

