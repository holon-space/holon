//! Transition: insert a new item with a generated name.
//! Always enabled — covers the `enabled = Some` baseline case.

use super::E2ETransition; // generated by declare_transitions!
use crate::reference::RefState;
use crate::sut::Sut;
use crate::transition::E2ETransitionFactory;
use proptest::prelude::*;
use proptest::strategy::BoxedStrategy;

#[derive(Clone, Debug)]
pub struct AddItem {
    pub name: String,
    /// id we expect the SUT to assign (we know it because both ref &
    /// SUT use sequential ids — in real code this comes back from SUT).
    pub expected_id: u32,
}

impl E2ETransitionFactory for AddItem {
    fn weighted_generator(state: &RefState) -> Option<(u32, BoxedStrategy<Self>)> {
        let next_id = state.next_id;
        let strat = "[a-z]{1,8}"
            .prop_map(move |name| AddItem {
                name,
                expected_id: next_id,
            })
            .boxed();
        Some((4, strat))
    }
}

impl E2ETransition for AddItem {
    fn preconditions(&self, state: &RefState) -> bool {
        // After shrinking, the recorded `expected_id` must still match
        // what the ref state would assign — otherwise the SUT and ref
        // would diverge silently.
        self.expected_id == state.next_id
    }

    fn apply_to_ref(&self, state: &mut RefState) {
        let id = state.add(self.name.clone());
        assert_eq!(id, self.expected_id, "ref-state id drift");
    }

    fn apply_to_sut(&self, sut: &mut Sut) {
        let prev = sut.items.insert(self.expected_id, self.name.clone());
        assert!(
            prev.is_none(),
            "SUT add: id {} already present",
            self.expected_id
        );
    }
}
