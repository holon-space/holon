# ── the source table ─────────────────────────────────────────────────


def _rows(table_heading, header):
    """The rows of the ONE table under `table_heading` whose first header cell
    is `header`.

    A section may hold more than one table — the `Runs` legend sits beside the
    timing table — so the header cell, not the heading, picks the table, and
    collection stops at the first line that is not a row.
    """
    text = SOURCE.read_text()
    after = text.split(table_heading, 1)
    if len(after) != 2:
        die(f"{SOURCE} has no '{table_heading}' section")
    out, inside = [], False
    for line in after[1].splitlines():
        s = line.strip()
        if s.startswith("## "):
            break
        cells = [c.strip() for c in s.strip("|").split("|")] if s.startswith("|") else []
        if not cells:
            inside = False
            continue
        if cells[0] == header:
            inside = True
            continue
        if not inside or set(cells[0]) <= set("- "):
            continue
        out.append(cells)
    if not out:
        die(f"{SOURCE}: '{table_heading}' has no '{header}' table — the parser drifted")
    return out


def _unbacktick(cell):
    m = re.match(r"^`(.+)`$", cell)
    return m.group(1) if m else cell


# What a row's `Runs` cell does. All three are timing-critical, so all three
# join the `timing-critical` test group and leave the load-tolerant complement;
# they differ in what runs them inside the gate's one quiet-hold step.
#   timing-step   `cargo nextest run --profile timing` selects it
#   own-recipe    a recipe of its own inside `just timing-gate` runs it, so the
#                 timing profile must NOT select it a second time
#   release-bench an `#[ignore]`d release bench; a debug gate step never runs it
RUNS_VALUES = ("timing-step", "own-recipe", "release-bench")
IN_GROUP = ("timing-step", "own-recipe")


def timing_rows():
    """(selector, runs, file, line) per timing-critical row."""
    rows = []
    for cells in _rows("## Timing-critical tests", "Selector"):
        selector = _unbacktick(cells[0])
        runs = cells[1]
        if runs not in RUNS_VALUES:
            die(f"row '{selector}' has Runs {runs!r}, not one of {RUNS_VALUES}")
        site = _unbacktick(cells[2])
        if ":" not in site:
            die(f"row '{selector}' names no file:line assertion site")
        path, _, line = site.rpartition(":")
        rows.append((selector, runs, path, int(line)))
    return rows


def cap_rows():
    """(test, p95_low_s, cap_s, evidence) per capped load-tolerant row."""
    rows = []
    for cells in _rows("### Current caps", "Test"):
        test = _unbacktick(cells[0])
        p95 = float(re.sub(r"[^0-9.]", "", cells[1]))
        cap = float(re.sub(r"[^0-9.]", "", cells[2]))
        rows.append((test, p95, cap, cells[3]))
    return rows


def _selectors(wanted):
    seen = []
    for selector, runs, _, _ in timing_rows():
        if runs in wanted and selector not in seen:
            seen.append(selector)
    return seen


def _filter(wanted):
    return " + ".join(f"({s})" for s in _selectors(wanted))


def load_tolerant_excluded():
    """Every term the load-tolerant `default-filter` excludes, as it writes it."""
    return _selectors(IN_GROUP) + list(OWN_RECIPE_OWNERS)


def parsed_owner_recipes():
    """`OWNER_RECIPES` as a tool that executes nothing reads it from this file."""
    tables = {}
    for node in ast.parse(pathlib.Path(__file__).read_text()).body:
        if not (isinstance(node, ast.Assign) and isinstance(node.value, ast.Dict)):
            continue
        merged = {}
        for key, value in zip(node.value.keys, node.value.values):
            if key is None:
                merged.update(tables[value.id])
            else:
                try:
                    merged[ast.literal_eval(key)] = ast.literal_eval(value)
                except ValueError:
                    die(f"{__file__}:{key.lineno}: {node.targets[0].id} holds a "
                        "non-literal entry; a tool that parses this file cannot read it")
        tables[node.targets[0].id] = merged
    return tables["OWNER_RECIPES"]


def timing_filter():
    """The whole timing group: what gets a core to itself, and what the
    load-tolerant profile is the complement of."""
    return _filter(IN_GROUP)


def profile_filter():
    """What `--profile timing` runs: the group minus the rows a recipe of their
    own already runs inside the same quiet-hold step."""
    return _filter(("timing-step",))


# ── the cap rule ─────────────────────────────────────────────────────


def cap_for(p95_low_s):
    lo, hi = CAP_FLOOR_S, CAP_CEILING_MULTIPLE * p95_low_s
    return max(lo, min(math.ceil(K * p95_low_s), hi))


def in_clamp(cap_s, p95_low_s):
    return CAP_FLOOR_S <= cap_s <= CAP_CEILING_MULTIPLE * p95_low_s


# ── generation ───────────────────────────────────────────────────────


def generated_block():
    f = timing_filter()
    p = profile_filter()
    lines = [
        BEGIN,
        "#",
        "# Source: docs/Testing/TimingCritical.md. Run `scripts/timing-split.py",
        "# generate` after editing that file; `check` fails when the two differ.",
        "",
        "[test-groups]",
        "# A timing test never contends with another: a quiet host is the point.",
        "timing-critical = { max-threads = 1 }",
        "",
        "[[profile.default.overrides]]",
        f'filter = "{f}"',
        'test-group = "timing-critical"',
        "",
        "# The quiet-hold step runs this profile, plus the `own-recipe` rows'",
        "# own recipes (`just latency-slo-gate`, `just org-deep-text-timing`),",
        "# which is why those rows are not selected here as well.",
        "[profile.timing]",
        f'default-filter = "{p}"',
        "",
        "# Everything else, at whatever load the lanes produce: the complement of",
        "# the timing set, minus the binaries that have a recipe of their own and",
        "# that `[profile.default]` already excludes. Dropping that second term",
        "# would silently start running the 119-case hand-authored replay inside",
        "# the wide sweep, without its skip list.",
        "[profile.load-tolerant]",
        f'default-filter = "not ({f}) & not ({OWN_RECIPE_BINARIES})"',
        "",
        "[profile.load-tolerant.junit]",
        '# Per-test durations feed the p95 the caps are derived from.',
        'path = "junit.xml"',
    ]
    for test, p95, cap, evidence in cap_rows():
        lines += [
            "",
            "[[profile.load-tolerant.overrides]]",
            f"# {evidence}.",
            f"# cap = {K} x p95_low {p95:.0f}s, within the {CAP_CEILING_MULTIPLE}x clamp.",
            f'filter = "test(={test})"',
            f'slow-timeout = {{ period = "60s", terminate-after = {math.ceil(cap / 60)} }}',
        ]
    lines.append(END)
    return "\n".join(lines) + "\n"


def splice(current, block):
    if BEGIN in current:
        head, rest = current.split(BEGIN, 1)
        if END not in rest:
            die(f"{NEXTEST} has a {BEGIN!r} with no {END!r}")
        tail = rest.split(END, 1)[1]
        return head + block + tail.lstrip("\n")
    sep = "" if current.endswith("\n\n") else ("\n" if current.endswith("\n") else "\n\n")
    return current + sep + block


def cmd_generate():
    current = NEXTEST.read_text()
    new = splice(current, generated_block())
    if new == current:
        print("timing-split: .config/nextest.toml already current")
        return 0
    NEXTEST.write_text(new)
    print(f"timing-split: rewrote the generated block in {NEXTEST}")
    return 0


# ── the duration ledger ──────────────────────────────────────────────


def cmd_record(junit_path, load_start, load_max):
    """JUnit -> the duration ledger, stamped with the RUN's observed load.

    The load is the CALLER's, required, never `load_now()`: that reads the load
    after the run ended, and one sample cannot describe an 8391-test sweep that
    spanned an hour at load 30 to 215. Stamped wrong it is worse than missing —
    a 479 s high-load duration entering the ledger as a QUIET measurement
    (observed: it moved one test's `p95_low` from 121 s to 479 s, which would
    have bought it a 1916 s cap). The `< QUIET_LOAD` filter in `p95_low` is the
    whole hang detector, and it can only work on an honest stamp.
    """
    path = pathlib.Path(junit_path)
    if not path.is_file():
        die(f"no JUnit file at {path}")
    import subprocess

    commit = subprocess.run(
        ["jj", "--ignore-working-copy", "log", "-r", "@-", "--no-graph", "-T",
         "commit_id.short()"],
        cwd=REPO, capture_output=True, text=True,
    ).stdout.strip() or "unknown"
    today = datetime.date.today().isoformat()
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    n = 0
    with open(LEDGER, "a") as fh:
        for case in ET.parse(path).getroot().iter("testcase"):
            name = case.get("name") or ""
            secs = case.get("time")
            if not name or secs is None:
                continue
            # A TIMEOUT is a CENSORED measurement and must never seed a p95.
            verdict = "green"
            for child in case:
                tag = child.tag.lower()
                if "error" in tag or "failure" in tag:
                    msg = (child.get("message") or "") + (child.text or "")
                    verdict = "timeout" if "timeout" in msg.lower() else "red"
            fh.write("\t".join([today, commit, name, f"{float(secs):.3f}",
                                f"{load_start:.2f}", f"{load_max:.2f}",
                                verdict]) + "\n")
            n += 1
    print(f"timing-split: recorded {n} test durations to {LEDGER} at load "
          f"{load_start:.2f}-{load_max:.2f}"
          + (f" (above the {QUIET_LOAD:.0f} quiet bar, so they feed no p95_low)"
             if max(load_start, load_max) >= QUIET_LOAD else ""))
    return 0


def cmd_seed(csv_path):
    """Seed the ledger from an A/B attribution run's `results.csv`.

    Columns: `pass,test,leg,exit,result,load_start,load_end,secs,log`. The CSV
    records `red` for a TIMEOUT too, and a TIMEOUT is a CENSORED measurement
    that must buy no headroom, so the verdict comes from the run's own nextest
    log, never from the exit code. A missing log is fatal: guessing would hand
    a hanging test the cap raise the rule exists to refuse.
    """
    path = pathlib.Path(csv_path)
    if not path.is_file():
        die(f"no results CSV at {path}")
    import csv

    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    seen = set(LEDGER.read_text().splitlines()) if LEDGER.is_file() else set()
    written, skipped, censored = 0, 0, 0
    with open(path) as fh, open(LEDGER, "a") as out:
        for row in csv.DictReader(fh):
            log = pathlib.Path(row["log"])
            if not log.is_file():
                die(f"row {row['pass']}/{row['leg']} {row['test']}: its log "
                    f"{log} is gone, so TIMEOUT cannot be told from a slow red")
            timed_out = any(
                line.lstrip().startswith("TIMEOUT [") and row["test"].rsplit("::", 1)[-1] in line
                for line in log.read_text(errors="replace").splitlines()
            )
            verdict = "timeout" if timed_out else row["result"]
            censored += timed_out
            line = "\t".join([
                datetime.date.today().isoformat(),
                f"ab44-{row['pass']}-{row['leg']}",
                row["test"],
                f"{float(row['secs']):.3f}",
                f"{float(row['load_start']):.2f}",
                f"{float(row['load_end']):.2f}",
                verdict,
            ])
            if line in seen:
                skipped += 1
                continue
            out.write(line + "\n")
            seen.add(line)
            written += 1
    print(f"timing-split: seeded {written} row(s) into {LEDGER} "
          f"({censored} censored as timeout, {skipped} already there)")
    return 0


def cmd_resolve(cargo_args):
    """Ask nextest which tests each generated filter selects, and red on none.

    A filter that selects nothing is the silent failure mode of this whole
    mechanism: the timing profile would run an empty set and report green, and
    a cap override would simply not apply. `test(=…)` is an exact match against
    the test's module path, which does NOT include the binary name, so a cap
    row named after its binary matches nothing.

    Needs the test binaries built, so this runs where they already are
    (`just load-tolerant-nextest`), not in `gate-arch`.
    """
    import subprocess

    # The CALLER's feature set, never `--all-features`: the workspace does not
    # build under the full union (a `ctor` initializer aborts), so a resolve
    # that picks its own features reports a compile failure as "the filter is
    # broken". `just load-tolerant-nextest` passes the same {{CANON}} the run used.
    if not cargo_args:
        die("resolve needs the run's cargo args, e.g. "
            "`resolve --workspace --features <CANON_FEATURES>`")

    def selects(*select_args):
        r = subprocess.run(
            ["cargo", "nextest", "list", *cargo_args, "--message-format", "json",
             *select_args],
            cwd=REPO, capture_output=True, text=True,
        )
        if r.returncode != 0:
            die(f"cargo nextest list failed for {select_args!r}:\n{r.stderr}")
        # nextest's JSON lists EVERY test and marks the filter result per test;
        # a non-matching one is present with a `filter-match.status` other than
        # `"matches"`. The top-level `test-count` is the UNFILTERED total (8515
        # for any expression), so it cannot be used either.
        # Counting the testcases wholesale returns the whole workspace's test
        # count for any expression, which made this check a false green that
        # reported "selects 8515 test(s)" for all three filters alike.
        listed = json.loads(r.stdout)
        return sum(
            1
            for suite in listed["rust-suites"].values()
            for case in suite["testcases"].values()
            if case.get("filter-match", {}).get("status") == "matches"
        )

    # `--run-ignored all`: an `#[ignore]`d row (the `own-recipe` deep-text
    # benches) is selected by its filter; nextest would otherwise mark it a
    # mismatch for being ignored.
    def by_filter(expr):
        return selects("--ignore-default-filter", "--run-ignored", "all", "-E", expr)

    # Per row, never only over the union: a row that selects nothing hides in
    # a non-empty union, and the load-tolerant complement keeps its test.
    fail = 0
    step_tests = 0
    seen = set()
    for selector, runs, _path, _line in timing_rows():
        if runs not in IN_GROUP or selector in seen:
            continue
        seen.add(selector)
        n = by_filter(selector)
        print(f"{'ok' if n else 'FAIL'}: {runs} row `{selector}` selects {n} test(s)")
        fail |= n == 0
        if runs == "timing-step":
            step_tests += n
    n = selects("--profile", "timing")
    print(f"{'ok' if n == step_tests else 'FAIL'}: `--profile timing` selects {n} "
          f"test(s), its timing-step rows {step_tests}")
    fail |= n != step_tests
    for test, _p95, _cap, _ev in cap_rows():
        n = by_filter(f"test(={test})")
        print(f"{'ok' if n else 'FAIL'}: cap row `{test}` selects {n} test(s)")
        fail |= n == 0

    print()
    if fail:
        print("timing-split: resolve FAILED — a filter that selects nothing is "
              "a cap or a whole profile that silently does not exist")
        return 1
    print("timing-split: resolve PASS")
    return 0


def ledger_rows():
    if not LEDGER.is_file():
        return []
    cutoff = (datetime.date.today()
              - datetime.timedelta(days=LEDGER_WINDOW_DAYS)).isoformat()
    out = []
    for line in LEDGER.read_text().splitlines():
        parts = line.split("\t")
        if len(parts) != 7 or parts[0] < cutoff:
            continue
        date, commit, test, secs, lo, hi, verdict = parts
        try:
            out.append((date, test, float(secs), float(lo), float(hi), verdict))
        except ValueError:
            continue
    return out


def p95_low(test):
    """The p95 over COMPLETED quiet runs, or None when the test has no p95.

    A test that only ever timed out has no p95 — a censored measurement buys no
    headroom. So does one with too few runs to percentile.
    """
    secs = sorted(
        s for _, t, s, lo, hi, v in ledger_rows()
        if t == test and v != "timeout" and max(lo, hi) < QUIET_LOAD
    )
    if len(secs) < MIN_RUNS_FOR_P95:
        return None
    return secs[min(len(secs) - 1, math.ceil(0.95 * len(secs)) - 1)]


def cmd_p95(test):
    p = p95_low(test)
    if p is None:
        print(f"{test}: NO p95 — fewer than {MIN_RUNS_FOR_P95} completed quiet "
              f"runs in the last {LEDGER_WINDOW_DAYS} days, so no cap raise")
        return 0
    print(f"{test}: p95_low {p:.1f}s -> cap {cap_for(p)}s "
          f"(K={K}, clamp {CAP_FLOOR_S}s..{CAP_CEILING_MULTIPLE}x)")
    return 0


# ── the budgeted kind alphabet ───────────────────────────────────────


def budgeted_kinds():
    """`transition_key()`'s universe, read from the macro invocation."""
    src = TRANSITIONS.read_text()
    after = src.split("crate::declare_e2e_transitions!", 1)
    if len(after) != 2:
        die(f"{TRANSITIONS} has no crate::declare_e2e_transitions! invocation")
    body = after[1]
    seen = 0
    start = None
    for i, c in enumerate(body):
        if c == "{":
            seen += 1
            if seen == 2:
                start = i + 1
                break
    if start is None:
        die("two opening braces (macro + enum) not found — the parser drifted")
    depth, end = 1, None
    for i in range(start, len(body)):
        if body[i] == "{":
            depth += 1
        elif body[i] == "}":
            depth -= 1
            if depth == 0:
                end = i
                break
    if end is None:
        die("unbalanced enum body — the parser drifted")
    kinds = set()
    for line in body[start:end].splitlines():
        s = line.strip()
        if not s or s.startswith("//"):
            continue
        m = re.match(r"([A-Za-z0-9_]+)", s)
        if not m:
            continue
        v = m.group(1)
        if v == SPLIT_VARIANT:
            kinds.update(f"{SPLIT_VARIANT}::{m2}" for m2 in MUTATIONS)
        else:
            kinds.add(v)
    if not kinds:
        die("extracted no variant names — the parser drifted")
    return kinds


def corpus_kinds():
    """What the hand-authored corpus can reach. Static: the cases are data."""
    kinds = set()
    for line in CORPUS.read_text().splitlines():
        s = line.strip()
        if not s or s.startswith("#"):
            continue
        case = json.loads(s)
        for t in case["transitions"]:
            name = t if isinstance(t, str) else next(iter(t))
            if name != SPLIT_VARIANT:
                kinds.add(name)
                continue
            mut = ((t[name] or {}).get("event", {}) or {}).get("mutation")
            if isinstance(mut, str):
                kinds.add(f"{SPLIT_VARIANT}::{mut}")
            elif isinstance(mut, dict):
                kinds.add(f"{SPLIT_VARIANT}::{next(iter(mut))}")
    return kinds


def cmd_coverage(logs):
    """Did the enforced rung touch enough of the kind alphabet?

    The observed kinds come from the rung's own log: `inv-sql-budget` prints one
    summary per transition keyed by `transition_key()`. No harness recorder and
    no cross-test ordering is involved.
    """
    universe = budgeted_kinds()
    if not logs:
        die("coverage needs at least one rung log")
    judging = len(logs) >= KIND_COVERAGE_WINDOW
    observed = set()
    pat = re.compile(r"\[inv-sql-budget[^\]]*\]\s+([A-Za-z0-9_]+(?:::[A-Za-z0-9_]+)?)[.:]")
    for log in logs:
        for line in pathlib.Path(log).read_text(errors="replace").splitlines():
            m = pat.search(line)
            if m and m.group(1) in universe:
                observed.add(m.group(1))
    missing = sorted(universe - observed)
    fraction = len(observed) / len(universe)
    print(f"timing-split: the rung touched {len(observed)}/{len(universe)} "
          f"budgeted kinds ({fraction:.0%}) over {len(logs)} run(s); "
          f"the bar is {KIND_COVERAGE_MIN:.0%}")
    if fraction + 1e-9 >= KIND_COVERAGE_MIN:
        return 0
    head = "FAIL" if judging else "WARN"
    print(f"{head}: {len(missing)} budgeted kind(s) the enforced rung never "
          f"judged, so the latency SLO is unmeasured for them:")
    for k in missing:
        print(f"  {k}")
    if not judging:
        print(f"WARN only: {len(logs)} log(s) is under the "
              f"{KIND_COVERAGE_WINDOW}-run window, and one random draw does not "
              f"touch all {len(universe)} kinds. Accumulate the window's logs "
              f"and run `coverage` over all of them to judge, or land the "
              f"deterministic tour so one run draws every kind.")
        return 0
    print("Land a deterministic tour so one run draws every kind, or "
          "widen the rung.")
    return 1


# ── the gate check ───────────────────────────────────────────────────


# What tells a reader that a span judges a duration. `wall-clock budget` is the
# established `#[ignore]` marker (#337) and counts: a test whose durations live
# in local bindings (`if long > short * 8`) shows no `Duration` on the comparing
# line, and the attribute is the author's explicit declaration.
DURATION_SIGNALS = re.compile(
    r"\belapsed\b|duration_since|Duration::from_|Instant::now|wall-clock budget"
    r"|_DEADLINE\b|_PATIENCE\b|_BUDGET\b|\bhard_budget\(\)|\bSLO\b"
)


def enclosing_fn_span(lines, line):
    """The 0-based [start, end) of the test enclosing 1-based `line`, or None.

    The span starts at the `fn`'s attributes, so `#[ignore = "wall-clock
    budget: …"]` is inside it, and ends at the function's closing brace.

    None when no `fn` encloses the line. Widening to the whole file instead
    would make the duration check vacuous — any line of a file that asserts a
    duration anywhere would pass, which is exactly the park rule 3 forbids.
    """
    i = line - 1
    fn = None
    while i >= 0:
        if re.match(r"\s*(pub\s+)?(async\s+)?(unsafe\s+)?fn\s", lines[i]):
            fn = i
            break
        i -= 1
    if fn is None:
        return None
    start = fn
    while start > 0 and re.match(r"\s*(#\[|//[/!]?|$)", lines[start - 1]):
        start -= 1
    depth, end = 0, len(lines)
    for j in range(fn, len(lines)):
        depth += lines[j].count("{") - lines[j].count("}")
        if depth <= 0 and j > fn:
            end = j + 1
            break
    return start, end


def asserts_a_duration(lines, line):
    span = enclosing_fn_span(lines, line)
    if span is None:
        return False
    start, end = span
    return bool(DURATION_SIGNALS.search("\n".join(lines[start:end])))


def cmd_check():
    fail = 0

    want = generated_block()
    current = NEXTEST.read_text()
    if BEGIN not in current:
        print(f"FAIL: {NEXTEST} has no generated block. Run "
              "`scripts/timing-split.py generate`.")
        fail = 1
    elif splice(current, want) != current:
        print(f"FAIL: {NEXTEST}'s generated block is not what "
              f"{SOURCE.name} generates. Run `scripts/timing-split.py generate`.")
        fail = 1
    else:
        print(f"ok: {NEXTEST} matches {SOURCE.name}")

    # Every timing row must name a real duration assertion. A content flake has
    # none, which is what keeps a bug-under-load out of the timing group.
    for selector, _runs, path, line in timing_rows():
        f = REPO / path
        if not f.is_file():
            print(f"FAIL: row '{selector}' names {path}, which does not exist")
            fail = 1
            continue
        lines = f.read_text(errors="replace").splitlines()
        if not 1 <= line <= len(lines):
            print(f"FAIL: row '{selector}' names {path}:{line}, past the file's "
                  f"{len(lines)} lines")
            fail = 1
            continue
        if not asserts_a_duration(lines, line):
            print(f"FAIL: row '{selector}' names {path}:{line}, where no duration "
                  "assertion is visible. A timing-group member must assert a "
                  "DURATION; a content assertion that only reds under load is a "
                  "RACE and stays load-tolerant (see the four classes).")
            fail = 1
    if not fail:
        print(f"ok: {len(timing_rows())} timing row(s) each name a duration assertion")

    # Every test the load-tolerant sweep skips names the recipe that runs it, so
    # a lane that drops the sweep for a test knows what to run instead.
    excluded = load_tolerant_excluded()
    missing = [t for t in excluded if t not in OWNER_RECIPES]
    stale = sorted(set(OWNER_RECIPES) - set(excluded))
    if missing:
        print("FAIL: the load-tolerant profile excludes term(s) that OWNER_RECIPES "
              "names no recipe for. Add to OWNER_RECIPES in scripts/timing-split.py:")
        for t in missing:
            print(f'    "{t}": "just timing-gate",')
        fail = 1
    if stale:
        print("FAIL: OWNER_RECIPES names term(s) the load-tolerant profile no longer "
              "excludes. Remove them from scripts/timing-split.py:")
        for t in stale:
            print(f'    "{t}"')
        fail = 1
    parsed_equal = parsed_owner_recipes() == OWNER_RECIPES
    if not parsed_equal:
        print("FAIL: OWNER_RECIPES read by parsing scripts/timing-split.py differs "
              "from the executed one. Keep it a dict of literals and `**` merges "
              "of earlier literal dicts.")
        fail = 1
    if not missing and not stale and parsed_equal:
        print(f"ok: each of the {len(set(excluded))} load-tolerant exclusion(s) names "
              "its recipe in OWNER_RECIPES")

    # Caps: within the clamp, and consistent with what the ledger now says.
    for test, p95, cap, _ in cap_rows():
        if not in_clamp(cap, p95):
            print(f"FAIL: {test} cap {cap:.0f}s is outside the clamp "
                  f"[{CAP_FLOOR_S}s, {CAP_CEILING_MULTIPLE}x{p95:.0f}s]")
            fail = 1
        measured = p95_low(test)
        if measured is None:
            print(f"ok (no fresh ledger data): {test} keeps its cited "
                  f"p95_low {p95:.0f}s")
            continue
        if not in_clamp(cap, measured):
            print(f"FAIL: {test} now measures p95_low {measured:.1f}s, and its "
                  f"cap {cap:.0f}s has left the clamp. Re-derive it: "
                  f"cap = {cap_for(measured)}s. A cap must not creep, and a test "
                  "that got faster gives its headroom back.")
            fail = 1
            continue
        print(f"ok: {test} cap {cap:.0f}s, ledger p95_low {measured:.1f}s "
              f"(cited {p95:.0f}s), within {CAP_CEILING_MULTIPLE}x")

    print()
    if fail:
        print("timing-split: FAILED")
        return 1
    print("timing-split: PASS")
    return 0


# ── the new-timing-assertion ratchet ─────────────────────────────────
#
# Signature = "<path>\t<class>\t<trimmed line>". The line NUMBER is dropped, so
# moving unrelated code is not a new violation (the `defensive-ratchet.sh`
# convention). The CLASS is the author's one-time judgement and is what makes
# the baseline reviewable: one line per site, saying which of the four classes
# it is.

BASELINE = REPO / "scripts/timing-assertions-baseline.txt"
CLASSES = ("timing", "liveness", "lower-bound", "harness", "virtual-clock")
SCAN_GLOBS = ("crates/*/src/**/*.rs", "crates/*/tests/**/*.rs",
              "frontends/*/src/**/*.rs", "frontends/*/tests/**/*.rs")
ASSERT_SITE = re.compile(r"\b(assert|assert_eq|assert_ne|prop_assert|prop_assert_eq)!|"
                         r"InvariantResult::Fail")
COMPARISON = re.compile(r"[<>]=?")


def assertion_sites():
    """Duration comparisons in ASSERTION position: (relpath, trimmed line)."""
    out = []
    for glob in SCAN_GLOBS:
        for f in sorted(REPO.glob(glob)):
            if "/target/" in str(f):
                continue
            lines = f.read_text(errors="replace").splitlines()
            for i, line in enumerate(lines):
                if not DURATION_SIGNALS.search(line) or not COMPARISON.search(line):
                    continue
                # The assertion macro may open up to 3 lines above the
                # comparison (`assert!(` then the expression).
                head = "\n".join(lines[max(0, i - 3):i + 1])
                if not ASSERT_SITE.search(head):
                    continue
                out.append((str(f.relative_to(REPO)), line.strip()))
    return out


def read_baseline():
    if not BASELINE.is_file():
        return {}
    known = {}
    for line in BASELINE.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) != 3:
            die(f"{BASELINE}: not three tab-separated fields: {line!r}")
        path, cls, text = parts
        if cls not in CLASSES:
            die(f"{BASELINE}: class {cls!r} is not one of {CLASSES}")
        known[(path, text)] = cls
    return known


def cmd_assertions(update=False):
    sites = assertion_sites()
    if update:
        known = read_baseline()
        BASELINE.parent.mkdir(parents=True, exist_ok=True)
        with open(BASELINE, "w") as fh:
            fh.write("# Every duration comparison in assertion position, with the "
                     "class its author assigned.\n")
            fh.write("# Classes: timing (the point is that the duration is SMALL; "
                     "must be in the\n")
            fh.write("#   timing group), liveness (the message reads 'it never "
                     "happened'), lower-bound\n")
            fh.write("#   (load can only make it pass), harness (plumbing: a wait "
                     "helper's own bound),\n")
            fh.write("#   virtual-clock (a PAUSED tokio clock: load cannot move "
                     "it at all).\n")
            fh.write("# See docs/Testing/TimingCritical.md. Regenerate with "
                     "`scripts/timing-split.py assertions --update`.\n")
            for path, text in sites:
                fh.write(f"{path}\t{known.get((path, text), 'UNCLASSIFIED')}\t{text}\n")
        n_new = sum(1 for s in sites if s not in known)
        print(f"timing-split: baseline written: {len(sites)} site(s), "
              f"{n_new} newly added as UNCLASSIFIED")
        return 0

    known = read_baseline()
    unclassified = [k for k, v in known.items() if v == "UNCLASSIFIED"]
    new = [s for s in sites if s not in known]
    fail = 0
    if new:
        fail = 1
        print(f"FAIL: {len(new)} duration assertion(s) this tree does not classify:")
        for path, text in new:
            print(f"  {path}\n    {text}")
        print("\nClassify each one (docs/Testing/TimingCritical.md, 'The four "
              "classes'):")
        print("  timing       the point is that the duration is SMALL -> add a row to")
        print("               docs/Testing/TimingCritical.md and regenerate")
        print("  liveness     the message reads 'it never happened' -> load-tolerant")
        print("  lower-bound  load can only make it pass -> load-tolerant")
        print("  harness      a wait helper's own bound, not a judgement")
        print("  virtual-clock  a PAUSED tokio clock -> load cannot move it")
        print("Then run `scripts/timing-split.py assertions --update` and set the "
              "class in scripts/timing-assertions-baseline.txt.")
    if unclassified:
        fail = 1
        print(f"FAIL: {len(unclassified)} baseline row(s) still say UNCLASSIFIED:")
        for path, text in sorted(unclassified):
            print(f"  {path}\n    {text}")

    # The baseline and the timing table must agree in BOTH directions, or one
    # of them quietly decides alone.
    timing_files = {path for _s, _r, path, _l in timing_rows()}
    classed_timing = {path for (path, _t), cls in known.items() if cls == "timing"}
    for (path, text), cls in sorted(known.items()):
        if cls == "timing" and path not in timing_files:
            print(f"FAIL: {path} is classed `timing` but no row of "
                  f"{SOURCE.name} names it, so the timing profile never selects "
                  f"it:\n    {text}")
            fail = 1
    # The other direction, and only where the scanner can see: a timing row
    # whose file HAS classified sites must have at least one classed `timing`,
    # or the table and the baseline contradict each other about the same lines.
    # Where the scanner sees nothing there is nothing to contradict — a
    # judgement may route through a verdict type or a ratio between two
    # `Duration`s, neither of which is a comparison in assertion position. Such
    # a row is held to `asserts_a_duration` at its named site instead.
    scanned = {path for path, _t in known}
    for selector, _runs, path, _line in timing_rows():
        if path in scanned and path not in classed_timing:
            print(f"FAIL: row '{selector}' names {path}, whose assertion sites "
                  f"this baseline all class as something OTHER than `timing`. "
                  f"The table says the duration is judged there and the baseline "
                  f"says it is not; one of the two is wrong.")
            fail = 1

    print()
    if fail:
        print("timing-split: assertions FAILED")
        return 1
    print(f"timing-split: assertions PASS — {len(sites)} site(s), all classified")
    return 0


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    cmd, args = argv[1], argv[2:]
    if cmd == "generate":
        return cmd_generate()
    if cmd == "check":
        return cmd_check()
    if cmd == "record":
        if len(args) != 3:
            die("record takes <junit.xml> <load_start> <load_max> — the RUN's "
                "observed load, which only the caller knows")
        return cmd_record(args[0], float(args[1]), float(args[2]))
    if cmd == "seed":
        if len(args) != 1:
            die("seed takes one results.csv path")
        return cmd_seed(args[0])
    if cmd == "resolve":
        return cmd_resolve(args)
    if cmd == "coverage":
        return cmd_coverage(args)
    if cmd == "assertions":
        return cmd_assertions(update="--update" in args)
    if cmd == "p95":
        if len(args) != 1:
            die("p95 takes one test name")
        return cmd_p95(args[0])
    print(__doc__)
    return 2


